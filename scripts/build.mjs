import { mkdir, rm, writeFile, cp } from 'node:fs/promises';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { build } from 'esbuild';
import { root, validateData } from './validate-data.mjs';
const { apps, svgs } = await validateData();
await writeFile(resolve(root, 'src/generated-icons.ts'), `// GENERATED by scripts/build.mjs. Edit assets/icons instead.\nexport const svgByPath: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(svgs)});\n`);
await rm(resolve(root, 'dist'), { recursive: true, force: true });
await mkdir(resolve(root, 'dist'), { recursive: true });
const types = spawnSync(process.execPath, [resolve(root,'node_modules/typescript/bin/tsc'), '-p', resolve(root,'tsconfig.json')], { cwd: root, stdio: 'inherit' });
if (types.status !== 0) process.exit(types.status ?? 1);
for (const [folder, format] of [['esm','esm'], ['cjs','cjs']]) {
  await build({ absWorkingDir: root, entryPoints: { index: 'src/index.ts', icons: 'src/icons.ts', react: 'src/react.ts' }, outdir: `dist/${folder}`, format, bundle: true, platform: 'neutral', target: 'es2020', external: ['react'], sourcemap: false, legalComments: 'none', charset: 'utf8' });
  await cp(resolve(root, 'dist/declarations/src'), resolve(root, `dist/${folder}`), { recursive: true });
}
await writeFile(resolve(root, 'dist/cjs/package.json'), '{"type":"commonjs"}\n');
await rm(resolve(root, 'dist/declarations'), { recursive: true, force: true });
console.log(`Built ESM, CommonJS and TypeScript declarations (${apps.length} records / ${Object.keys(svgs).length} SVGs)`);
